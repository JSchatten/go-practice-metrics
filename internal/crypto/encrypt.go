package crypto

import (
	"crypto/rand"
	"crypto/rsa"
)

// EncryptWithPublicKey шифрует данные с использованием RSA публичного ключа по алгоритму PKCS#1 v1.5.
//
// Функция использует криптографически безопасный генератор случайных чисел для
// добавления padding'а, что делает шифрование недетерминированным и защищает от атак.
// Подходит для шифрования небольших объёмов данных (до длины модуля ключа минус 11 байт).
//
// Параметры:
//   - pub: указатель на RSA публичный ключ
//   - data: байтовый срез с данными для шифрования
//
// Возвращает:
//   - []byte: зашифрованные данные, длина равна длине модуля ключа в байтах
//   - error: ошибка, если данные слишком длинные, ключ недействителен или произошла ошибка шифрования
func EncryptWithPublicKey(pub *rsa.PublicKey, data []byte) ([]byte, error) {
	return rsa.EncryptPKCS1v15(rand.Reader, pub, data)
}

// DecryptWithPrivateKey расшифровывает данные с использованием RSA приватного ключа по алгоритму PKCS#1 v1.5.
//
// Функция удаляет padding и возвращает оригинальные данные. Требует доступа к приватному
// ключу и корректных зашифрованных данных. При неудаче возвращает ошибку.
//
// Параметры:
//   - priv: указатель на RSA приватный ключ
//   - data: байтовый срез с зашифрованными данными (длина должна совпадать с длиной модуля ключа)
//
// Возвращает:
//   - []byte: расшифрованные оригинальные данные
//   - error: ошибка, если данные повреждены, ключ недействителен или произошла ошибка расшифрования
func DecryptWithPrivateKey(priv *rsa.PrivateKey, data []byte) ([]byte, error) {
	return rsa.DecryptPKCS1v15(rand.Reader, priv, data)
}
