// Package repository
// определяет общий интерфейс для хранения и получения метрик.
//
// Цель пакета — предоставить абстракцию над различными способами хранения метрик,
// такими как файл (FileRepository) и база данных PostgreSQL (MetricRepo),
// позволяя использовать их посредством единого интерфейса.
//
// Интерфейс MetricRepository описывает основные операции:
//   - Сохранение и загрузку метрик (в виде байт, для сериализации/десериализации).
//   - Получение и обновление отдельных метрик (для прямого доступа).
//   - Проверку соединения (ping).
//
// Это позволяет легко переключаться между реализациями без изменения бизнес-логики.
package repository

import (
	"context"

	models "github.com/JSchatten/go-practice-metrics/internal/model"
)

// MetricRepository — общий интерфейс для работы с хранилищем метрик.
// Реализуется как FileRepository, так и MetricRepo (PostgreSQL).
// Позволяет абстрагироваться от конкретного способа хранения.
type MetricRepository interface {
	// SaveMetrics сохраняет сериализованные метрики в хранилище.
	// Должен быть потокобезопасным. Возвращает ошибку при неудаче.
	SaveMetrics(data []byte) error

	// LoadMetrics загружает сериализованные метрики из хранилища.
	// Возвращает данные и ошибку (если файл не существует, может вернуть пустые данные).
	LoadMetrics() ([]byte, error)

	// GetMetricByID возвращает метрику по её идентификатору.
	// Возвращается указатель на метрику и ошибка (например, ErrNotFound).
	GetMetricByID(ctx context.Context, id string) (*models.Metrics, error)

	// UpdateMetric обновляет значение метрики.
	// Для счётчиков (counter) значение накапливается, для измерителей (gauge) — заменяется.
	UpdateMetric(ctx context.Context, m *models.Metrics) error

	// Ping проверяет доступность хранилища.
	// Используется для проверки соединения с базой данных или доступности файла.
	Ping(ctx context.Context) error
}
