func main() {
	var analyzers []*analysis.Analyzer

	// Добавляем все стандартные анализаторы из passes
	analyzers = append(analyzers,
		asmdecl.Analyzer,
		assign.Analyzer,
		atomic.Analyzer,
		atomicalign.Analyzer,
		buildssa.Analyzer,
		buildtag.Analyzer,
		cgocall.Analyzer,
		composite.Analyzer,
		copylock.Analyzer,
		ctrlflow.Analyzer,
		deepequalerrors.Analyzer,
		defers.Analyzer,
		directive.Analyzer,
		errorsas.Analyzer,
		fieldalignment.Analyzer,
		findcall.Analyzer,
		framepointer.Analyzer,
		httpresponse.Analyzer,
		ifaceassert.Analyzer,
		inspect.Analyzer,
		loopclosure.Analyzer,
		lostcancel.Analyzer,
		nilfunc.Analyzer,
		nilness.Analyzer,
		pkgfact.Analyzer,
		printf.Analyzer,
		reflectvaluecompare.Analyzer,
		shadow.Analyzer,
		shift.Analyzer,
		sigchanyzer.Analyzer,
		slog.Analyzer,
		sortslice.Analyzer,
		stdmethods.Analyzer,
		stringintconv.Analyzer,
		structtag.Analyzer,
		testinggoroutine.Analyzer,
		tests.Analyzer,
		timeformat.Analyzer,
		unmarshal.Analyzer,
		unreachable.Analyzer,
		unsafeptr.Analyzer,
		unusedresult.Analyzer,
		unusedwrite.Analyzer,
		usesgenerics.Analyzer,
	)

	for _, a := range simple.Analyzers {
		analyzers = append(analyzers, a.Analyzer)
	}

	for _, stage := range staticcheck.Analyzers {
		analyzers = append(analyzers, stage.Analyzer)
	}

	for _, stage := range stylecheck.Analyzers {
		analyzers = append(analyzers, stage.Analyzer)
	}

	analyzers = append(analyzers, unused.Analyzer.Analyzer)
	analyzers = append(analyzers, checkers.Analyzer)

	// кастомный
	analyzers = append(analyzers, checkers.Analyzer)

	// Удаляем дубликаты по имени
	filtered := make([]*analysis.Analyzer, 0, len(analyzers))
	seen := make(map[string]bool)

	for _, a := range analyzers {
		if a == nil || a.Name == "" {
			continue
		}
		if seen[a.Name] {
			continue
		}
		seen[a.Name] = true
		filtered = append(filtered, a)
	}

	multichecker.Main(filtered...)
}
